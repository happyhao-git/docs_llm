import { expect, test, type APIRequestContext } from '@playwright/test'

test.describe.serial('LinkAPI documentation on disposable database', () => {
  let session: APIRequestContext
  let cookies: Awaited<ReturnType<APIRequestContext['storageState']>>['cookies']

  test.beforeAll(async ({ playwright, baseURL }) => {
    session = await playwright.request.newContext({ baseURL })
    const response = await session.post('/api/admin/login', { data: { username: 'verification', password: 'docs-verification-only' } })
    expect(response.ok()).toBeTruthy()
    cookies = (await session.storageState()).cookies
  })

  test.beforeEach(async ({ context }) => {
    await context.addCookies(cookies)
  })

  test.afterAll(async () => {
    await session?.dispose()
  })

  test('collapses inactive sidebar groups and keeps the current article visible', async ({ page }) => {
    await page.goto('/docs/windows-install-claude')
    const groupButtons = page.locator('.sidebar-group-label')
    const totalGroups = await groupButtons.count()
    expect(totalGroups).toBeGreaterThan(1)

    const currentLink = page.locator('.sidebar-link[aria-current="page"]')
    await expect(currentLink).toBeVisible()
    const currentGroup = currentLink.locator('xpath=ancestor::div[contains(@class, "sidebar-group")]')
    await expect(currentGroup.locator('.sidebar-group-label')).toHaveAttribute('aria-expanded', 'true')
    await expect(page.locator('.sidebar-group-label[aria-expanded="false"]')).toHaveCount(totalGroups - 1)

    const otherGroup = page.locator('.sidebar-group-label[aria-expanded="false"]').first()
    const otherGroupId = await otherGroup.getAttribute('id')
    expect(otherGroupId).toBeTruthy()
    await otherGroup.click()
    const expandedOtherGroup = page.locator(`#${otherGroupId}`)
    await expect(expandedOtherGroup).toHaveAttribute('aria-expanded', 'true')
    await expect(expandedOtherGroup.locator('xpath=following-sibling::div')).toBeVisible()
    await expect(currentLink).toBeVisible()

    await page.goto('/')
    await expect(page.locator('.sidebar-group-label[aria-expanded="true"]')).toHaveCount(0)
    await page.locator('.sidebar-group-label').first().click()
    await expect(page.locator('.sidebar-group-label').first()).toHaveAttribute('aria-expanded', 'true')
  })

  test('publishes only changes and displays a reviewable summary', async ({ page }) => {
    await page.goto('/admin')
    await expect(page.locator('.admin-editor')).toBeVisible()
    if (await page.getByRole('button', { name: '发布站点', exact: true }).isVisible()) {
      await page.getByRole('button', { name: '发布站点', exact: true }).click()
      await expect(page.getByRole('dialog')).toContainText('首次发布')
      await page.getByRole('button', { name: '确认发布', exact: true }).click()
    }
    await expect(page.getByRole('button', { name: '已是最新', exact: true })).toBeDisabled()
    await expect(page.getByRole('button', { name: '保存草稿', exact: true })).toBeDisabled()
    await page.screenshot({ path: '/tmp/linkapi-admin-latest.png' })

    const title = page.locator('#article-title')
    const originalTitle = await title.inputValue()
    await title.fill(`${originalTitle}（测试）`)
    await expect(page.getByRole('button', { name: '请先保存草稿', exact: true })).toBeDisabled()
    await title.fill(originalTitle)
    await expect(page.getByRole('button', { name: '已是最新', exact: true })).toBeDisabled()

    const editor = page.locator('.editor-pane textarea')
    const originalMarkdown = await editor.inputValue()
    await editor.fill(`${originalMarkdown}\n\n独立测试库中的发布验证。`)
    await page.getByRole('button', { name: '保存草稿', exact: true }).click()
    await page.getByRole('button', { name: '发布站点', exact: true }).click()
    await expect(page.locator('.publish-counts > div').nth(1)).toContainText('1')
    await expect(page.locator('.publish-changes')).toContainText(originalTitle)
    await page.screenshot({ path: '/tmp/linkapi-publish-review.png' })
    await page.getByRole('button', { name: '取消', exact: true }).click()
    await editor.fill(originalMarkdown)
    await page.getByRole('button', { name: '保存草稿', exact: true }).click()
    await expect(page.getByRole('button', { name: '已是最新', exact: true })).toBeDisabled()
  })

  test('renders the customer page, favicon, search and next article', async ({ page, request }) => {
    const errors: string[] = []
    page.on('pageerror', (error) => errors.push(error.message))
    await page.goto('/docs/windows-install-codex')
    await expect(page.locator('.doc-section > h1')).toHaveText('Windows 安装与配置 Codex')
    await page.evaluate(() => document.fonts.ready)
    await expect(page.locator('.brand-mark')).toHaveJSProperty('naturalWidth', 64)
    expect((await request.get('/favicon.svg')).headers()['content-type']).toContain('image/svg+xml')
    expect((await request.get('/favicon.ico')).headers()['content-type']).toContain('image/')
    expect((await request.get('/apple-touch-icon.png')).ok()).toBeTruthy()
    expect((await request.get('/site.webmanifest')).ok()).toBeTruthy()
    await page.locator('.support-card img').evaluate((img: HTMLImageElement) => img.decode())
    await page.screenshot({ path: '/tmp/linkapi-docs-desktop.png' })
    await page.keyboard.press('Control+k')
    await expect(page.getByRole('searchbox')).toBeFocused()
    await page.getByRole('searchbox').fill('Claude')
    await expect(page.locator('.search-result').first()).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(page.getByRole('dialog')).not.toBeVisible()
    await page.locator('.pagination-card.next').click()
    await expect(page).toHaveURL(/mac-install-codex/)
    await expect(page.locator('.doc-section > h1')).toHaveText('Mac / Linux 安装与配置 Codex')
    await expect.poll(() => page.evaluate(() => window.scrollY)).toBe(0)
    await page.getByRole('button', { name: '切换到深色模式' }).click()
    await page.screenshot({ path: '/tmp/linkapi-docs-dark.png' })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    expect(errors).toEqual([])
  })

  test('keeps mobile navigation and reading within the viewport', async ({ page }) => {
    await page.setViewportSize({ width: 390, height: 844 })
    await page.goto('/docs/windows-install-codex')
    await expect(page.locator('.doc-section > h1')).toBeVisible()
    await page.evaluate(() => document.fonts.ready)
    await page.screenshot({ path: '/tmp/linkapi-docs-mobile.png' })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.getByRole('button', { name: '打开导航' }).click()
    await expect(page.locator('.docs-sidebar')).toHaveClass(/open/)
    await page.locator('.sidebar-link').nth(1).click()
    await expect(page).toHaveURL(/mac-install-codex/)
    await expect(page.locator('.docs-sidebar')).not.toHaveClass(/open/)
    await page.getByRole('button', { name: /搜索文档/ }).click()
    await expect(page.getByRole('searchbox')).toBeFocused()
  })
  test('introduces all guides on a clear homepage and supports keyboard search', async ({page}) => {
    await page.goto('/')
    await expect(page.locator('.home-heading h1')).toHaveText('使用文档')
    await expect(page.locator('.guide-card')).toHaveCount(4)
    await expect(page.locator('.guide-card-links a')).toHaveCount(6)
    await expect(page.locator('.docs-sidebar')).not.toContainText('管理密钥与 API 用量')
    await expect(page.locator('.docs-sidebar')).not.toContainText('LINKAPI DOCS')
    await expect(page.locator('.sidebar-intro')).toHaveText('LinkAPI 开发者文档')
    await expect(page.locator('.sidebar-intro')).toHaveAttribute('href', '/')
    await expect(page.locator('.docs-sidebar')).not.toContainText('文档概览')
    await page.evaluate(()=>document.fonts.ready)
    await page.screenshot({path:'/tmp/linkapi-home-desktop.png',fullPage:true})
    const trigger=page.getByRole('button',{name:'搜索文档',exact:true})
    await trigger.click()
    await expect(page.getByRole('searchbox')).toBeFocused()
    await page.getByRole('searchbox').fill('chmod')
    await expect(page.locator('.search-result').first()).toBeVisible()
    await expect(page.locator('.search-result').first()).toContainText('定位到')
    await page.screenshot({path:'/tmp/linkapi-search.png'})
    await page.keyboard.press('Enter')
    await expect(page.locator('.doc-section h1')).toContainText('Mac')
    await expect(page).toHaveURL(/#.+/)
    await expect(page.getByRole('dialog')).not.toBeVisible()
    await page.locator('.sidebar-intro').click()
    await expect(page.locator('.home-heading')).toBeVisible()
    await trigger.click()
    await page.getByRole('searchbox').fill('<img src=x onerror=alert(1)>')
    await expect(page.locator('.no-results')).toContainText('没有找到')
    await page.keyboard.press('Escape')
    await expect(trigger).toBeFocused()
  })

  test('opens support images, preserves legacy sections and copies complete long prompts', async({page,context})=>{
    await page.goto('/#windows-install-codex--获取-api-key')
    await expect(page).toHaveURL(/docs\/windows-install-codex/)
    await expect(page.locator('[id="windows-install-codex--获取-api-key"]')).toBeAttached()
    await page.goto('/docs/codex-image-generation')
    const qr=page.locator('.support-card img')
    await expect(qr).toHaveJSProperty('complete',true)
    await qr.evaluate((img: HTMLImageElement) => img.decode())
    await expect(page.locator('.support-title')).toHaveText('微信技术支持')
    await expect(page.locator('.support-card')).not.toContainText('请勿发送密钥')
    const qrBox=(await qr.boundingBox())!
    expect(qrBox.width).toBeGreaterThanOrEqual(340)
    expect(qrBox.width).toBeLessThanOrEqual(370)
    expect(qrBox.height/qrBox.width).toBeCloseTo(1131/888,2)
    await qr.focus(); await page.keyboard.press('Enter')
    await expect(page.getByRole('dialog',{name:'技术支持二维码'})).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(qr).toBeFocused()
    const block=page.locator('.code-block').first()
    await expect(block).toHaveClass(/is-collapsed/)
    await block.getByRole('button',{name:'展开完整内容'}).click()
    await expect(block).not.toHaveClass(/is-collapsed/)
    await context.grantPermissions(['clipboard-read','clipboard-write'])
    await block.getByRole('button',{name:'复制代码'}).click()
    await expect(block.getByRole('button',{name:'已复制',exact:true})).toBeVisible()
    const copied=await page.evaluate(()=>navigator.clipboard.readText())
    expect(copied).toContain('请使用 $skill-creator')
    expect(copied.trim().endsWith('不要输出任何 API Key 内容。')).toBe(true)
    await page.goto('/docs/windows-install-claude#windows-install-claude--填写网关信息')
    await expect(page.locator('h3[id="windows-install-claude--填写网关信息"]')).toBeVisible()
    await expect(page.locator('.markdown-body details')).toHaveCount(0)
    await expect(page.locator('img[src$="b0793545-7d9b-4613-9ad1-90bb5dafa293.png"]')).toBeVisible()
  })

  test('switches editor modes, traps modal focus and protects unsaved edits', async({page})=>{
    await page.goto('/admin')
    await expect(page.locator('.editor-pane textarea')).toBeVisible()
    await page.getByRole('button',{name:'预览',exact:true}).click()
    await expect(page.locator('.editor-pane')).not.toBeVisible()
    await expect(page.locator('.admin-preview .support-card')).toBeVisible()
    await page.getByRole('button',{name:'编辑',exact:true}).click()
    await expect(page.locator('.preview-pane')).not.toBeVisible()
    await page.getByRole('button',{name:'分屏',exact:true}).click()
    const trigger=page.getByRole('button',{name:'站点设置',exact:true})
    await trigger.click()
    const dialog=page.getByRole('dialog')
    await expect(dialog).toBeVisible()
    const last=dialog.getByRole('button',{name:'保存设置'})
    await last.focus(); await page.keyboard.press('Tab')
    expect(await dialog.evaluate(el=>el.contains(document.activeElement))).toBe(true)
    await page.keyboard.press('Escape'); await expect(trigger).toBeFocused()
    const editor=page.getByRole('textbox',{name:'Markdown 正文'})
    const original=await editor.inputValue()
    await editor.fill(original+'\n未保存的验证')
    page.once('dialog',d=>d.dismiss())
    await page.getByRole('button',{name:'退出登录'}).click()
    await expect(editor).toHaveValue(original+'\n未保存的验证')
    await editor.fill(original)
    await expect(page.getByRole('button',{name:'已是最新',exact:true})).toBeDisabled()
    await page.setViewportSize({width:390,height:844})
    await page.getByRole('button',{name:'预览',exact:true}).click()
    await expect(page.locator('.admin-preview')).toBeVisible()
    await expect(page.locator('.admin-sidebar')).not.toBeVisible()
    await page.screenshot({path:'/tmp/linkapi-admin-mobile.png'})
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  })

  test('fits light and dark layouts across phone, tablet and desktop widths', async({page})=>{
    const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
    for(const width of [320,390,768,1280,1920]) {
      await page.setViewportSize({width,height:900})
      for(const path of ['/','/docs/windows-install-codex']) {
        await page.goto(path)
        await expect(page.locator('.docs-main h1').first()).toBeVisible()
        await page.evaluate(()=>document.fonts.ready)
        expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
        if(path.startsWith('/docs/')) {
          const qr=page.locator('.support-card img')
          await expect(qr).toBeVisible()
          await qr.evaluate((img: HTMLImageElement) => img.decode())
          const box=(await qr.boundingBox())!
          expect(box.width).toBeGreaterThanOrEqual(220)
          expect(box.width).toBeLessThanOrEqual(370)
          expect(box.height/box.width).toBeCloseTo(1131/888,2)
          expect(box.x).toBeGreaterThanOrEqual(0)
          expect(box.x+box.width).toBeLessThanOrEqual(width)
        }
        if(width===390 || width===1280) await page.screenshot({path:`/tmp/linkapi-${path==='/'?'home':'article'}-${width}.png`})
      }
    }
    await page.getByRole('button',{name:'切换到深色模式'}).click()
    await page.screenshot({path:'/tmp/linkapi-article-1920-dark.png'})
    await page.goto('/admin/login')
    await expect(page.locator('.login-panel')).toBeVisible()
    await page.screenshot({path:'/tmp/linkapi-login.png'})
    expect(errors).toEqual([])
  })

})
