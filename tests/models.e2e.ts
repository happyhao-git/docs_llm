import { expect, test } from '@playwright/test'

test.describe('Model catalog', () => {
  test('loads recognizable provider marks in light and dark themes', async ({ page }) => {
    await page.goto('/models')
    const icons = page.locator('.platform-list .platform-icon')
    await expect(icons).toHaveCount(6)
    await expect.poll(() => icons.evaluateAll(images => images.every(image => (image as HTMLImageElement).complete && (image as HTMLImageElement).naturalWidth > 0))).toBe(true)
    expect(await icons.evaluateAll(images => images.every(image => image.getAttribute('alt') === '' && image.getAttribute('aria-hidden') === 'true'))).toBe(true)
    for (const platform of ['openai', 'anthropic', 'grok', 'deepseek', 'kimi', 'zhipu']) {
      await expect(page.locator(`.platform-icon[data-platform="${platform}"]`)).toHaveAttribute('src', `/platform-icons/${platform}.svg?v=20261104b`)
      expect(await page.request.get(`/platform-icons/${platform}.svg`).then(response => response.status())).toBe(200)
    }
    await page.screenshot({ path: '/tmp/linkapi-provider-icons-light.png', animations: 'disabled' })
    await page.getByRole('button', { name: '切换到深色模式' }).click()
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
    await expect(page.locator('.platform-icon[data-platform="anthropic"]')).toHaveCSS('filter', 'none')
    await expect(page.locator('.platform-icon[data-platform="kimi"]')).toHaveAttribute('src', '/platform-icons/kimi-dark.svg?v=20261104b')
    await expect(page.locator('.platform-icon[data-platform="zhipu"]')).toHaveCSS('filter', 'brightness(0) invert(1)')
    await expect.poll(() => icons.evaluateAll(images => images.every(image => (image as HTMLImageElement).complete && (image as HTMLImageElement).naturalWidth > 0))).toBe(true)
    await page.screenshot({ path: '/tmp/linkapi-provider-icons-dark.png', animations: 'disabled' })
  })

  test('filters real data, compares billing modes and persists deep links', async ({ page }) => {
    await page.goto('/models')
    await expect(page.getByRole('heading', { name: '模型广场' })).toBeVisible()
    await expect(page.locator('.coefficient-badge')).toContainText('0.08x')
    await page.getByRole('textbox', { name: '搜索模型' }).fill('gpt-5.5')
    await expect(page.locator('.model-row')).toHaveCount(1)
    await expect(page).toHaveURL(/q=gpt-5.5/)
    await page.locator('.model-name').click()
    await expect(page.locator('.model-details')).toContainText('计费基准')
    await expect(page.locator('.model-details')).toContainText('输入 > 272K token')
    await page.getByRole('button', { name: '余额', exact: true }).click()
    await expect(page.locator('.coefficient-badge')).toContainText('0.2')
    await page.reload()
    await expect(page.getByRole('textbox', { name: '搜索模型' })).toHaveValue('gpt-5.5')
    await expect(page.getByRole('button', { name: '余额', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await page.getByRole('button', { name: '清空搜索' }).click()
    await page.locator('.platform-list button').filter({ hasText: 'Kimi' }).click()
    await expect(page.locator('.model-row')).toHaveCount(2)
    await page.getByRole('button', { name: '订阅', exact: true }).click()
    await expect(page.getByRole('combobox', { name: '使用分组' })).toContainText('一卡通')
  })

  test('displays equivalent subscription prices and compares each billing scenario', async ({ page }) => {
    for (const model of ['gpt-6.1-terra', 'gpt-5.5']) {
      await page.goto(`/models?group=12&q=${model}`)
      await page.getByRole('button', { name: model, exact: true }).click()
      await expect(page.locator('.coefficient-badge')).toHaveText('折算 0.08x')
      await expect(page.locator('.scenario-heading strong')).toHaveText(['标准', '长上下文', 'Fast / Priority', 'Flex'])
      const standalone = await page.locator('.comparison-table .model-price strong').allTextContents()
      await page.getByRole('combobox', { name: '使用分组' }).selectOption('67')
      await page.getByRole('button', { name: model, exact: true }).click()
      await expect(page.locator('.coefficient-badge')).toHaveText('折算 0.08x')
      expect(await page.locator('.comparison-table .model-price strong').allTextContents()).toEqual(standalone)
      await expect(page.locator('.row-coefficient')).toHaveText('0.08x')
      await expect(page.locator('.comparison-table tbody tr').first().locator('.comparison-ratio')).toHaveText(['2x 标准价', model === 'gpt-5.5' ? '2.5x 标准价' : '2x 标准价', '0.5x 标准价'])
    }
    await page.goto('/models?billing=balance&group=26&q=gpt-6.1-terra')
    await page.getByRole('button', { name: 'gpt-6.1-terra', exact: true }).click()
    await expect(page.locator('.coefficient-badge')).toHaveText('折算 0.2x')
    await expect(page.locator('.comparison-table tbody tr').first().locator('.model-price strong')).toHaveText(['实际价格 ¥0.2', '实际价格 ¥0.4', '实际价格 ¥0.4', '实际价格 ¥0.1'])
  })

  test('copies model IDs, handles empty searches and restores focus from mobile drawer', async ({ page, context }) => {
    await context.grantPermissions(['clipboard-read', 'clipboard-write'])
    await page.goto('/models?q=gpt-5.5')
    await page.locator('.model-row').hover()
    await page.getByRole('button', { name: '复制 gpt-5.5', exact: true }).click()
    expect(await page.evaluate(() => navigator.clipboard.readText())).toBe('gpt-5.5')
    await page.getByRole('textbox', { name: '搜索模型' }).fill('does-not-exist-model')
    await expect(page.getByText('没有找到匹配的模型')).toBeVisible()
    await page.setViewportSize({ width: 390, height: 844 })
    const trigger = page.locator('.models-platform-trigger')
    await trigger.click()
    await expect(page.getByRole('dialog', { name: '模型平台' })).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(trigger).toBeFocused()
    await expect(page.getByRole('dialog', { name: '模型平台' })).toHaveCount(0)
  })

  test('fits desktop, tablet, mobile and dark mode including expanded prices', async ({ page }) => {
    await page.goto('/models?q=gpt-5.5')
    await page.locator('.model-name').click()
    for (const width of [1440, 768, 390]) {
      await page.setViewportSize({ width, height: 960 })
      await expect(page.locator('.model-details')).toBeVisible()
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      await page.screenshot({ path: `/tmp/linkapi-models-verified-${width}.png`, animations: 'disabled' })
    }
    await page.getByRole('button', { name: '切换到深色模式' }).click()
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
    await page.screenshot({ path: '/tmp/linkapi-models-verified-dark.png', animations: 'disabled' })
    await page.reload()
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  })

  test('shows first-load and stale data states without synthetic prices', async ({ page, request }) => {
    const catalog = await (await request.get('/api/public/models')).json()
    await page.route('**/api/public/models/refresh', route => route.fulfill({ json: { catalog, status: 'updated', retryAfterSeconds: 0 } }))
    await page.route('**/api/public/models', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: '模型目录正在同步，请稍后重试' }) }))
    await page.goto('/models')
    await expect(page.getByRole('heading', { name: '目录暂时不可用' })).toBeVisible()
    await expect(page.locator('.model-row')).toHaveCount(0)
    await page.unroute('**/api/public/models')
    await page.getByRole('button', { name: '重新加载' }).click()
    await expect(page.locator('.model-row').first()).toBeVisible()
    await page.route('**/api/public/models', async route => {
      const response = await route.fetch(); const catalog = await response.json(); catalog.stale = true
      await route.fulfill({ response, json: catalog })
    })
    await page.route('**/api/public/models/refresh', route => route.fulfill({ json: { catalog: { ...catalog, stale: true }, status: 'failed', retryAfterSeconds: 60 } }))
    await page.getByRole('button', { name: '刷新模型目录' }).click()
    await expect(page.locator('.models-notice')).toContainText('上次更新')
    await expect(page.locator('.model-row').first()).toBeVisible()
  })

  test('protects admin settings and applies exchange changes immediately', async ({ page, request }) => {
    expect((await request.get('/api/admin/models')).status()).toBe(401)
    await page.goto('/admin/models')
    await expect(page).toHaveURL(new RegExp('admin/login'))
    await page.getByLabel('用户名').fill('verification')
    await page.getByLabel('密码', { exact: true }).fill('docs-verification-only')
    await page.getByRole('button', { name: '登录', exact: true }).click()
    await expect(page).toHaveURL(new RegExp('/admin/models$'))
    const field = page.getByRole('spinbutton', { name: 'OpenAI订阅每额度人民币成本' })
    await field.fill('0.04')
    await page.getByRole('button', { name: '保存配置' }).click()
    await expect(page.getByText('配置已保存，公开页面立即生效。')).toBeVisible()
    const changed = await (await request.get('/api/public/models')).json()
    expect(changed.groups.find((g: any) => g.id === '12').cnyPerCredit).toBe('0.04')
    await field.fill('0.02')
    await page.getByRole('button', { name: '保存配置' }).click()
    await expect(page.getByText('配置已保存，公开页面立即生效。')).toBeVisible()
    const cookies = await page.context().cookies()
    const authCookie = cookies.filter(c => c.name === 'docs_session').map(c => `${c.name}=${c.value}`).join('; ')
    expect((await request.put('/api/admin/models/settings', { headers: { cookie: authCookie }, data: {} })).status()).toBe(403)
  })
})
