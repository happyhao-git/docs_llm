import { expect, test } from '@playwright/test'
import { directoryPoolFixture } from './fixtures/directory-pools'

test.beforeEach(async ({ page }) => {
  await page.route('**/api/public/models', route => route.fulfill({ json: directoryPoolFixture() }))
  await page.route('**/api/public/models/refresh', route => route.abort())
})

test('selects the vendor before the pool, keeps the all-access plan and caches all changes', async ({ page }) => {
  let reads = 0, syncs = 0
  page.on('request', r => { if (r.url().endsWith('/api/public/models')) reads++; if (r.url().endsWith('/api/public/models/refresh')) syncs++ })
  await page.goto('/models')
  const vendor = page.getByRole('combobox', { name: '模型厂商', exact: true }), pool = page.getByRole('combobox', { name: '账号池', exact: true })
  const group = page.getByRole('combobox', { name: '使用分组', exact: true })
  await expect(vendor).toHaveValue(''); await expect(pool).toHaveCount(0)
  await expect(group).toHaveValue('67')
  await vendor.selectOption('anthropic')
  await expect(group).toHaveValue('67'); await expect(pool).toHaveValue('claude-default')
  await expect(pool.locator('option')).toHaveText(['Claude【默认】', 'Claude【企业】'])
  await pool.selectOption('claude-pro')
  await expect(page.locator('.model-row')).toHaveCount(1)
  await expect(page.locator('.model-row .model-price strong')).toContainText('¥0.3')
  await page.reload(); await expect(pool).toHaveValue('claude-pro')
  await group.selectOption('44'); await expect(pool).toHaveValue('claude-pro')
  await group.selectOption('67'); await expect(pool).toHaveValue('claude-pro')
  await vendor.selectOption('deepseek'); await expect(group).toHaveValue('67')
  await expect(pool).toHaveValue('deepseek-default')
  await pool.selectOption('deepseek-official'); await expect(page.locator('.model-row')).toHaveCount(2)
  await expect(page.locator('.model-row .model-price strong').first()).toContainText('¥0.45')
  await vendor.selectOption(''); await expect(pool).toHaveCount(0)
  await expect(page.locator('[data-model-key="deepseek:deepseek-test"] .model-price strong')).toContainText('¥0.12')
  expect(new URL(page.url()).searchParams.has('pool')).toBe(false)
  expect(reads).toBe(1); expect(syncs).toBe(0)
})

test('supports old links, incompatible group changes, single pools, no pools and reset', async ({ page }) => {
  const vendor = page.getByRole('combobox', { name: '模型厂商', exact: true }), pool = page.getByRole('combobox', { name: '账号池', exact: true })
  const group = page.getByRole('combobox', { name: '使用分组', exact: true })
  await page.goto('/models?billing=subscription&platform=all&group=67&pool=claude-pro')
  await expect(vendor).toHaveValue('anthropic'); await expect(pool).toHaveValue('claude-pro')
  await expect(page).toHaveURL(/vendor=anthropic/)
  await group.selectOption('12'); await expect(vendor).toHaveValue(''); await expect(pool).toHaveCount(0)
  await expect(vendor.locator('option')).toHaveText(['全部厂商', 'OpenAI'])
  await group.selectOption('67'); await vendor.selectOption('grok')
  await expect(pool.locator('option')).toHaveCount(1)
  await group.selectOption(''); await expect(pool).toHaveValue('grok-only')
  await expect(page.locator('.directory-group-name')).toHaveText('一卡通 订阅')
  await expect(page.locator('.model-price strong')).toContainText('¥0.21')
  await group.selectOption('65'); await expect(pool).toHaveCount(0)
  await expect(page.locator('.model-price strong')).toContainText('¥0.02')
  await page.getByRole('button', { name: '重置', exact: true }).click()
  await expect(group).toHaveValue(''); await expect(vendor).toHaveValue(''); await expect(pool).toHaveCount(0)
  await expect(page.getByRole('combobox', { name: '排序依据', exact: true })).toHaveValue('platform')
  await page.goto('/models?billing=subscription&platform=all&group=67&vendor=deepseek&pool=claude-pro')
  await expect(pool).toHaveValue('deepseek-default'); await expect(page).not.toHaveURL(/pool=/)
  await page.getByRole('button', { name: '余额', exact: true }).click()
  await expect(pool).toHaveCount(0); await expect(vendor).toHaveValue('')
})

